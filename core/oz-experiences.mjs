export function mergeOzExperiences(state){
  if (!Array.isArray(state.experienceLibrary)) state.experienceLibrary=[];
  let added=0;
  for (const entry of OZ_EXPERIENCES){
    if (state.experienceLibrary.some(x=>x.sourceKey===entry.sourceKey || x.id===entry.id)) continue;
    // Existing user references remain unchanged. Canonical imported formats can coexist.
    state.experienceLibrary.push(structuredClone(entry));added++;
  }
  return added;
}
